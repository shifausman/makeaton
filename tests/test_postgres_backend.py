"""Check the SQL adapter without requiring a live Supabase connection."""

import unittest
from unittest.mock import patch

import app
from postgres_backend import PostgresConnection


class FakeCursor:
    def __init__(self, rows):
        self.rows = list(rows)

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchall(self):
        rows, self.rows = self.rows, []
        return rows

    def __iter__(self):
        return iter(self.rows)


class FakeRaw:
    def __init__(self):
        self.calls = []

    def execute(self, sql, args):
        self.calls.append((sql, args))
        return FakeCursor([{"id": 7}] if "RETURNING id" in sql else [])


class PostgresAdapterTest(unittest.TestCase):
    def setUp(self):
        self.db = PostgresConnection.__new__(PostgresConnection)
        self.db.raw = FakeRaw()

    def test_placeholders_insert_ids_and_transactions(self):
        self.assertEqual(self.db.execute("INSERT INTO plans(name,price_cents) VALUES(?,?)",
                                         ("Starter", 1200)).lastrowid, 7)
        self.assertEqual(self.db.raw.calls[-1],
                         ("INSERT INTO plans(name,price_cents) VALUES(%s,%s) RETURNING id", ("Starter", 1200)))
        self.db.execute("INSERT INTO sessions(token_hash,user_id,expires_at) VALUES(?,?,?)", ("x", 1, "tomorrow"))
        self.assertNotIn("RETURNING", self.db.raw.calls[-1][0])
        self.db.execute("BEGIN IMMEDIATE")
        self.assertEqual(self.db.raw.calls[-1], ("BEGIN", None))

    def test_postgres_schema_uses_identity_columns(self):
        class SchemaRecorder:
            def __init__(self):
                self.schema = ""
                self.statements = []

            def executescript(self, schema):
                self.schema = schema

            def execute(self, sql, args=()):
                self.statements.append(sql)

            def close(self):
                pass

        recorder = SchemaRecorder()
        with patch.object(app, "DATABASE_URL", "postgresql://example"), patch.object(app, "connect", return_value=recorder):
            app.init_db(seed=False)
        self.assertIn("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", recorder.schema)
        self.assertNotIn("PRAGMA", recorder.schema)
        self.assertTrue(any("ADD COLUMN IF NOT EXISTS features" in sql for sql in recorder.statements))


if __name__ == "__main__":
    unittest.main()
